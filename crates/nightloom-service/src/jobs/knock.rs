//! The away server's wake-up calls (nightshift item 781, blocker 2040: never
//! kept on; woken just before each job).
//!
//! The Fly machine stops when idle and starts on the next request. A GitHub
//! Actions scheduled workflow in the Nightloom repository requests the
//! server's public page ([`KNOCK_PATH`], no token) [`LEAD_MINUTES`] before
//! each run of a job the server keeps a copy of; the server then stays up
//! while a job is due or running (`nightloom serve --idle-exit`) and exits
//! by itself after. GitHub runs scheduled workflows late, often by 5–15
//! minutes (`external`: GitHub's docs say runs may be delayed at busy
//! times), hence the lead.
//!
//! [`workflow`] writes the file from the job list: each run's knock time in
//! UTC over the next year, so a job on his clock is knocked at both of its
//! UTC hours (summer and winter) and the file does not go stale at a
//! daylight-saving change — one knock a day lands an hour off and costs
//! the machine's ten idle minutes. Nothing of a job but its times goes in the file —
//! the repository may be public.

use chrono::{DateTime, Datelike, Duration, Timelike, Utc};

use super::Job;

/// How long before a run the knock comes.
pub const LEAD_MINUTES: i64 = 15;
/// How far ahead the times are read: a year, both sides of daylight saving.
pub const HORIZON_DAYS: i64 = 366;
/// The page the knock asks for: the phone page, which needs no token; the
/// query marks it as a knock so the server counts it as being used.
pub const KNOCK_PATH: &str = "/?wake=job";
/// The most cron lines written; past this, one knock every 15 minutes.
const MAX_LINES: usize = 40;

/// The cron lines (UTC, `m h * * dow`) that knock before every run of
/// `jobs` (paused ones and stand-ins left out) from `now` on. Pure.
pub fn crons(jobs: &[Job], now: DateTime<Utc>) -> Vec<String> {
    use std::collections::{BTreeMap, BTreeSet};
    let end = now + Duration::days(HORIZON_DAYS);
    // (minute, hour) → weekdays (0 = Sunday).
    let mut at: BTreeMap<(u32, u32), BTreeSet<u32>> = BTreeMap::new();
    for job in jobs.iter().filter(|j| !j.paused && !j.stand_in) {
        let mut t = now;
        for _ in 0..4096 {
            let next = job.next_after(t);
            if next <= t || next > end {
                break;
            }
            let k = next - Duration::minutes(LEAD_MINUTES);
            at.entry((k.minute(), k.hour()))
                .or_default()
                .insert(k.weekday().num_days_from_sunday());
            t = next;
        }
    }
    // Every day at one time → `*`; every hour at one minute → `m * * * *`.
    let mut daily: BTreeMap<u32, BTreeSet<u32>> = BTreeMap::new();
    let mut lines = Vec::new();
    for ((m, h), days) in &at {
        if days.len() == 7 {
            daily.entry(*m).or_default().insert(*h);
        } else {
            let list: Vec<String> = days.iter().map(u32::to_string).collect();
            lines.push(format!("{m} {h} * * {}", list.join(",")));
        }
    }
    for (m, hours) in daily {
        if hours.len() == 24 {
            lines.push(format!("{m} * * * *"));
        } else {
            let list: Vec<String> = hours.iter().map(u32::to_string).collect();
            lines.push(format!("{m} {} * * *", list.join(",")));
        }
    }
    if lines.len() > MAX_LINES {
        return vec!["*/15 * * * *".into()];
    }
    lines.sort();
    lines
}

/// The workflow file for the server at `url`. Pure.
pub fn workflow(url: &str, jobs: &[Job], now: DateTime<Utc>) -> String {
    let url = url.trim().trim_end_matches('/');
    let lines = crons(jobs, now);
    let mut schedule = String::new();
    for l in &lines {
        schedule.push_str(&format!("    - cron: \"{l}\"\n"));
    }
    if lines.is_empty() {
        // No job keeps a copy on the server: a workflow with no schedule
        // never runs (by hand only).
        schedule.push_str("    # no away jobs: nothing to knock for\n");
    }
    format!(
        "# Wakes Nightloom's away server {LEAD_MINUTES} minutes before each job it keeps a copy of\n\
         # (nightshift item 781). Generated by `nightloom jobs-knock` from the Mac's job list on\n\
         # {date}; run it again after adding or re-timing a job. Times are UTC. Scheduled workflows\n\
         # run only from the default branch.\n\
         name: Wake the away server\n\
         on:\n\
         {sched}  workflow_dispatch:\n\
         permissions: {{}}\n\
         jobs:\n\
         \x20 knock:\n\
         \x20   runs-on: ubuntu-latest\n\
         \x20   timeout-minutes: 5\n\
         \x20   steps:\n\
         \x20     - name: Ask for the phone page (no token; starts a stopped machine)\n\
         \x20       run: curl -fsS -o /dev/null --max-time 120 --retry 3 --retry-delay 15 \"{url}{KNOCK_PATH}\"\n",
        date = now.format("%Y-%m-%d"),
        sched = if lines.is_empty() {
            format!("  schedule: []\n{schedule}")
        } else {
            format!("  schedule:\n{schedule}")
        },
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::jobs::{Jobs, NewJob};

    fn job(every: &str, tz: &str) -> Job {
        let d = std::env::temp_dir().join(format!(
            "nl-knock-{}-{}",
            std::process::id(),
            uuid::Uuid::new_v4().simple()
        ));
        let jobs = Jobs::open_in(d.clone(), None);
        let now: DateTime<Utc> = "2026-11-17T12:00:00Z".parse().unwrap();
        let v = jobs
            .create(
                NewJob {
                    every: every.into(),
                    text: "check".into(),
                    tz: Some(tz.into()),
                    ..Default::default()
                },
                now,
            )
            .unwrap();
        let _ = std::fs::remove_dir_all(&d);
        v.job
    }

    /// 8:00 AM in Los Angeles is 16:00 UTC in winter (knocked at 15:45) and
    /// 15:00 in summer (14:45); a UTC job has one line.
    #[test]
    fn a_morning_job_is_knocked_a_quarter_hour_early_in_utc() {
        let now = "2026-11-17T12:00:00Z".parse().unwrap();
        let j = job("every day at 8am", "America/Los_Angeles");
        assert_eq!(crons(std::slice::from_ref(&j), now), vec!["45 14,15 * * *"]);
        let u = job("every day at 8am", "UTC");
        assert_eq!(crons(&[u], now), vec!["45 7 * * *"]);
        let mut paused = j;
        paused.paused = true;
        assert!(crons(&[paused], now).is_empty());
    }

    /// Across the March change both UTC hours are knocked.
    #[test]
    fn a_daylight_saving_change_knocks_at_both_hours() {
        let now = "2027-03-05T12:00:00Z".parse().unwrap();
        let j = job("every day at 8am", "America/Los_Angeles");
        assert_eq!(crons(&[j], now), vec!["45 14,15 * * *"]);
    }

    #[test]
    fn weekday_and_hourly_jobs_fold_into_short_lines() {
        let now = "2026-11-17T12:00:00Z".parse().unwrap();
        let w = job("every weekday at 9am", "UTC");
        assert_eq!(crons(&[w], now), vec!["45 8 * * 1,2,3,4,5"]);
        let h = job("every 30 minutes", "UTC");
        let lines = crons(&[h], now);
        assert!(lines.len() <= 2, "{lines:?}");
        assert!(lines.iter().all(|l| l.ends_with(" * * * *")), "{lines:?}");
    }

    #[test]
    fn the_file_names_times_and_the_page_and_nothing_of_the_job() {
        let now = "2026-11-17T12:00:00Z".parse().unwrap();
        let mut j = job("every day at 8am", "America/Los_Angeles");
        j.title = "Private title".into();
        j.text = "private message".into();
        let f = workflow("https://example.fly.dev/", &[j], now);
        assert!(f.contains("- cron: \"45 14,15 * * *\""), "{f}");
        assert!(f.contains("https://example.fly.dev/?wake=job"));
        assert!(!f.contains("Private") && !f.contains("private message"));
        assert!(f.contains("permissions: {}"));
    }
}
